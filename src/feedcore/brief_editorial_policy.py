"""Shared LLM instructions: four-dimension briefs and noise filtering."""

FOUR_DIMENSION_QUALITY = """\
**四维与噪声过滤（必遵）**
在写入「事实」「背景」「产生的影响」「反面观点 / 数据矛盾点」之前，先根据正文主线识别核心报道对象与议题；只保留对读者理解该议题有直接帮助的信息。
**有据分析（必遵）**：每一条归纳必须能从用户给出的「正文」或文章块中追溯到依据；禁止凭空捏造正文未出现的实体、数字、因果与结论；禁止凭常识或新闻标题脑补细节。背景、影响、反面观点亦须源自正文表述（或文中明确引述的人物/机构说法）；若仅有暗示而无明示，用「报道指」「文中称」等弱化措辞并紧贴原文，否则不写。宁可删句，不可空穴来风。
须主动排除、不得写入任一分节的内容包括：站点导航与栏目菜单、分享/关注/点赞引导、视频播放器控件文案（如 Pause、Share）、订阅与 APP 推广、「扫描二维码」「点击确认登录」、责任编辑与版权声明、广告话术、荐读区中与其它报道标题的简单链接堆砌、与主报道明显无关的同期短讯或 filler。
每条「- 」列表项须单独贡献新信息：禁止同义反复，禁止把弱相关花絮、纯气氛描写或重复同一事实的换表述当作多条要点。宁少勿滥、信息密度优先于条数；事实以可核实主干为主，背景写因果与脉络，影响写文中明示或可合理推断的后果，反面只写对立观点、质疑或数据/口径不一致处。
**四要素齐备（硬约束）**：事实、背景、产生的影响、反面观点/数据矛盾点四条缺一不可；每一节必须至少有一条**有信息量的**要点（不得以单句「正文未涉及」「需核实」「未见矛盾」或括号占位敷衍一整节）。若基于正文无法同时满足四维实质内容，则**不要写四维草稿**：整篇输出且仅输出一行 `BRIEF_REJECTED_INCOMPLETE_DIMENSIONS`（勿添加其它字符），以便上游丢弃本条数据。禁止捏造。"""

AGGREGATE_BRIEF_EXTRA = """\
**多篇综合时**：合并同一事件或同一信源的重复表述，避免在四维中重复罗列；各篇自带的导航类噪声同样不得进入综合简报。
**事件级四要素**：每个事件/议题小节仍须四维齐备；若某条来源材料无法支撑完整四维，**省略该条或该事件**，勿用单句占位凑齐。
**有据综合**：每条结论须标明或可回溯至具体 Article 正文中的表述；禁止把多篇标题拼成虚构叙事，禁止空穴来风。"""
